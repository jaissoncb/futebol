import { act, render, screen, waitFor, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { GameFlow } from '../draw/GameFlow'
import * as service from './match-service'
import type { FutebolDataClient } from '../lib/data-client'
import { group, players } from './test-fixtures'

vi.mock('./match-service', async (original) => ({ ...await original<typeof service>(), saveMatchDraw: vi.fn() }))
const client = {} as FutebolDataClient
const saveMock = vi.mocked(service.saveMatchDraw)
beforeEach(() => { saveMock.mockReset(); saveMock.mockImplementation((_client, id) => Promise.resolve(id)) })
afterEach(() => vi.restoreAllMocks())

async function result(user: ReturnType<typeof userEvent.setup>) {
  await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
  await user.click(screen.getByRole('button', { name: 'Selecionar todos' }))
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  return screen.findByRole('region', { name: 'Resultado do sorteio' })
}
async function save(user: ReturnType<typeof userEvent.setup>) {
  await user.click(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
  await screen.findByText(/Partida salva e sorteio aceito/)
}

describe('persistência real no fluxo da Fase 7', () => {
  it('retira o aviso de saída somente após salvamento confirmado e notifica rascunho limpo', async () => {
    const user = userEvent.setup(), onDraftChange = vi.fn()
    const view = render(<GameFlow client={client} group={group} players={players} onDraftChange={onDraftChange} />)
    const pristine = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(pristine)
    expect(pristine.defaultPrevented).toBe(false)
    await result(user)
    expect(onDraftChange).toHaveBeenLastCalledWith(true)
    const draft = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(draft)
    expect(draft.defaultPrevented).toBe(true)
    await save(user)
    expect(onDraftChange).toHaveBeenLastCalledWith(false)
    const saved = new Event('beforeunload', { cancelable: true })
    window.dispatchEvent(saved)
    expect(saved.defaultPrevented).toBe(false)
    view.unmount()
  })
  it.each(['owner', 'admin'] as const)('gera UUID antes da chamada e finaliza uma única vez (%s)', async (role) => {
    const user = userEvent.setup(), onSaved = vi.fn()
    const uuid = vi.spyOn(crypto, 'randomUUID')
    saveMock.mockImplementation((_client, id) => { expect(uuid).toHaveBeenCalledOnce(); return Promise.resolve(id) })
    render(<GameFlow client={client} group={{ ...group, role }} players={players} onSaved={onSaved} />)
    await result(user); expect(uuid).not.toHaveBeenCalled()
    await save(user)
    expect(saveMock).toHaveBeenCalledOnce(); expect(onSaved).toHaveBeenCalledWith(uuid.mock.results[0]!.value)
    expect(saveMock.mock.calls[0]![2]).toMatchObject({ group_id: group.id, team_count: 2, players_on_court: 1 })
    expect(screen.queryByRole('button', { name: 'Salvar e aceitar sorteio' })).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Novo sorteio' })).toBeDisabled()
  })
  it('bloqueia double-submit e mudanças enquanto aguarda resposta', async () => {
    const user = userEvent.setup()
    let resolve!: (id: string) => void
    saveMock.mockImplementation(() => new Promise<string>((r) => { resolve = r }))
    render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    await user.dblClick(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
    expect(saveMock).toHaveBeenCalledOnce()
    expect(screen.getByRole('button', { name: 'Salvando e aceitando…' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Editar jogo' })).toBeDisabled()
    await act(() => { resolve(saveMock.mock.calls[0]![1]); return Promise.resolve() })
    await screen.findByText(/Partida salva e sorteio aceito/)
  })
  it('retry após rede incerta preserva UUID, conteúdo e snapshots mesmo com mudança no elenco', async () => {
    const user = userEvent.setup(), uuid = vi.spyOn(crypto, 'randomUUID')
    saveMock.mockRejectedValueOnce(new Error('private network detail'))
    const view = render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    await user.click(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('pode já ter sido salva')
    expect(screen.queryByText('private network detail')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: 'Editar jogo' })).toBeDisabled()
    const first = saveMock.mock.calls[0]!
    view.rerender(<GameFlow client={client} group={group} players={[]} />)
    expect(screen.getByText(/P1 · Nível/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Tentar salvar novamente' }))
    await screen.findByText(/Partida salva e sorteio aceito/)
    expect(uuid).toHaveBeenCalledOnce()
    expect(saveMock.mock.calls[1]![1]).toBe(first[1]); expect(saveMock.mock.calls[1]![2]).toBe(first[2])
  })
  it.each([
    ['balanced', 'Equilibrado', 'balanced-positions-v2'],
    ['competitive', 'Competitivo', 'competitive-starters-v2'],
  ])('salva %s com seed, métricas históricas e retry idempotente após ajustes e novo sorteio', async (mode, label, version) => {
    const user = userEvent.setup()
    saveMock.mockRejectedValueOnce(new Error('timeout'))
    render(<GameFlow client={client} group={group} players={players} />)
    const select = screen.getByRole('combobox', { name: 'Modo de sorteio' })
    expect(select).toHaveValue('classic')
    await user.selectOptions(select, mode)
    const region = await result(user)
    expect(within(region).getByText(label, { exact: true })).toBeInTheDocument()
    expect(within(region).getByText(/Diferença entre médias dos titulares/)).toBeInTheDocument()
    const team = within(region).getAllByRole('article')[0]!
    const reserve = within(team).getByRole('region', { name: /Reservas do Time/ })
    const starter = within(team).getByRole('region', { name: /Em quadra do Time/ })
    const swap = async () => {
      await user.click(within(reserve).getByRole('button', { name: /^Selecionar para ajuste/ }))
      await user.click(within(starter).getByRole('button', { name: 'Trocar titular/reserva' }))
    }
    await swap()
    expect(within(region).getByText(/Ajustado manualmente/)).toBeInTheDocument()
    await user.click(within(region).getByRole('button', { name: 'Novo sorteio' }))
    await user.click(screen.getByRole('button', { name: 'Descartar ajustes e sortear' }))
    await screen.findByText('2 sorteio(s) nesta partida. Somente o último será aceito.')
    expect(within(region).queryByText(/Ajuste aplicado/)).not.toBeInTheDocument()
    await swap()
    await user.click(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
    await screen.findByRole('alert')
    const [, id, payload] = saveMock.mock.calls[0]!
    expect(payload.draw_runs.map(run => [run.algorithm_version, run.accepted])).toEqual([[version, false], [version, true]])
    expect(new Set(payload.draw_runs.map(run => run.seed)).size).toBe(2)
    const means = payload.teams.map(({ team_index }) => {
      const ids = payload.assignments.filter(assignment => assignment.team_index === team_index).map(assignment => assignment.player_id)
      return payload.participants.filter(player => ids.includes(player.player_id)).reduce((sum, player) => sum + player.skill_rating_snapshot, 0) / ids.length
    })
    expect(payload.draw_runs[1]!.balance_score).toBeCloseTo(Math.abs(means[0]! - means[1]!), 12)
    expect(payload.participants).toHaveLength(players.length)
    expect(payload.assignments.filter(assignment => assignment.assignment_source === 'manual')).toHaveLength(2)
    await user.click(screen.getByRole('button', { name: 'Tentar salvar novamente' }))
    await screen.findByText(/Partida salva e sorteio aceito/)
    expect(saveMock.mock.calls[1]![1]).toBe(id)
    expect(saveMock.mock.calls[1]![2]).toBe(payload)
  })

  it('exige abandono explícito antes de editar conteúdo divergente e usa outro UUID', async () => {
    const user = userEvent.setup()
    saveMock.mockRejectedValueOnce(new Error('timeout'))
    render(<GameFlow client={client} group={group} players={players} />)
    await result(user); await user.click(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
    await screen.findByRole('alert')
    await user.click(screen.getByRole('button', { name: 'Abandonar tentativa e editar' }))
    await user.click(screen.getByRole('button', { name: 'Manter tentativa' }))
    expect(screen.getByRole('button', { name: 'Editar jogo' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Abandonar tentativa e editar' }))
    expect(screen.getByRole('alertdialog')).toHaveTextContent('poderá criar outra partida')
    await user.click(screen.getByRole('button', { name: 'Abandonar e editar' }))
    await user.click(screen.getByRole('button', { name: 'Editar jogo' }))
    await user.type(screen.getByLabelText(/Nome/), 'Partida editada')
    await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
    await user.click(screen.getByRole('button', { name: 'Sortear times' }))
    await screen.findByRole('region', { name: 'Resultado do sorteio' }); await save(user)
    expect(saveMock.mock.calls[1]![1]).not.toBe(saveMock.mock.calls[0]![1])
    expect(saveMock.mock.calls[1]![2].name).toBe('Partida editada')
    expect(saveMock.mock.calls[1]![2].draw_runs).toHaveLength(1)
  })
  it('mantém todos rerolls em sequência e exatamente o último aceito', async () => {
    const user = userEvent.setup()
    render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    for (let i = 0; i < 2; i++) { await user.click(screen.getByRole('button', { name: 'Novo sorteio' })); await waitFor(() => expect(screen.getByRole('button', { name: 'Novo sorteio' })).toBeEnabled()) }
    await save(user)
    const runs = saveMock.mock.calls[0]![2].draw_runs
    expect(runs.map((r) => [r.run_number, r.accepted])).toEqual([[1, false], [2, false], [3, true]])
    expect(new Set(runs.map((r) => r.seed)).size).toBe(3)
  })
  it('descarta os runs anteriores quando a seleção é alterada', async () => {
    const user = userEvent.setup()
    render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    await user.click(screen.getByRole('button', { name: 'Novo sorteio' }))
    await waitFor(() => expect(screen.getByRole('button', { name: 'Novo sorteio' })).toBeEnabled())
    await user.click(screen.getByRole('button', { name: 'Voltar aos participantes' }))
    await user.click(screen.getAllByRole('checkbox')[0]!)
    await user.click(screen.getByRole('button', { name: 'Sortear times' }))
    await screen.findByRole('region', { name: 'Resultado do sorteio' }); await save(user)
    expect(saveMock.mock.calls[0]![2].draw_runs).toHaveLength(1)
    expect(saveMock.mock.calls[0]![2].participants).toHaveLength(3)
  })
  it('descarta runs quando a configuração muda, mas preserva ao voltar sem alterações', async () => {
    const user = userEvent.setup()
    render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    await user.click(screen.getByRole('button', { name: 'Editar jogo' }))
    await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
    await user.click(screen.getByRole('button', { name: 'Sortear times' }))
    await screen.findByRole('region', { name: 'Resultado do sorteio' })
    expect(screen.getByText(/2 sorteio\(s\)/)).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Editar jogo' }))
    await user.clear(screen.getByLabelText('Em quadra por time'))
    await user.type(screen.getByLabelText('Em quadra por time'), '2')
    await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
    await user.click(screen.getByRole('button', { name: 'Sortear times' }))
    await screen.findByRole('region', { name: 'Resultado do sorteio' }); await save(user)
    expect(saveMock.mock.calls[0]![2].draw_runs).toHaveLength(1)
    expect(saveMock.mock.calls[0]![2].assignments.every((a) => !a.starts_as_reserve)).toBe(true)
  })
  it('persiste a troca manual final, mantendo seed/version do draw-base', async () => {
    const user = userEvent.setup()
    render(<GameFlow client={client} group={group} players={players} />)
    const region = await result(user)
    await user.click(within(region).getAllByRole('button', { name: /^Selecionar para ajuste/ })[0]!)
    await user.click(within(region).getAllByRole('button', { name: 'Trocar com selecionado' })[0]!)
    await save(user)
    expect(saveMock.mock.calls[0]![2].assignments.filter((a) => a.assignment_source === 'manual')).toHaveLength(2)
    expect(saveMock.mock.calls[0]![2].draw_runs[0]).toMatchObject({ accepted: true, algorithm_version: 'balanced-candidates-v1' })
  })
  it('invalida resultado quando níveis/goleiros do elenco mudam antes de salvar', async () => {
    const user = userEvent.setup()
    const view = render(<GameFlow client={client} group={group} players={players} />)
    await result(user)
    view.rerender(<GameFlow client={client} group={group} players={players.map((p) => ({ ...p, skill_rating: 1 }))} />)
    expect(screen.queryByRole('button', { name: 'Salvar e aceitar sorteio' })).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Revisar participantes' }))
    await user.click(screen.getByRole('button', { name: 'Sortear times' }))
    await screen.findByRole('region', { name: 'Resultado do sorteio' }); await save(user)
    expect(saveMock.mock.calls[0]![2].draw_runs).toHaveLength(1)
    expect(saveMock.mock.calls[0]![2].participants.every((p) => p.skill_rating_snapshot === 1)).toBe(true)
  })
})

async function addRule(user: ReturnType<typeof userEvent.setup>, kind: string, first: number, target: string) {
  await user.click(screen.getByRole('button', { name: 'Adicionar regra' }))
  await user.selectOptions(screen.getByLabelText('Tipo de regra'), kind)
  await user.selectOptions(screen.getByLabelText('Primeiro jogador'), players[first]!.id)
  await user.selectOptions(screen.getByLabelText(kind === 'fixed' ? 'Time fixo' : 'Segundo jogador'), target)
  await user.click(screen.getByRole('button', { name: 'Ativar regra' }))
}

it('protege regras no ajuste e no novo sorteio e usa o mesmo contrato no retry', async () => {
  const user = userEvent.setup()
  saveMock.mockRejectedValueOnce(new Error('timeout'))
  render(<GameFlow client={client} group={group} players={players} />)
  await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
  await user.click(screen.getByRole('button', { name: 'Selecionar todos' }))
  await addRule(user, 'together', 0, players[1]!.id)
  await addRule(user, 'fixed', 0, '0')
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  const region = await screen.findByRole('region', { name: 'Resultado do sorteio' })
  const [blue, red] = within(region).getAllByRole('article') as [HTMLElement, HTMLElement]
  await user.click(within(blue).getByRole('button', { name: 'Selecionar para ajuste P1' }))
  await user.click(within(red).getAllByRole('button', { name: 'Trocar com selecionado' })[0]!)
  expect(within(region).getByRole('status')).toHaveTextContent(/viola a regra Pessoa 1 e Pessoa 2/)
  await user.click(within(blue).getByRole('button', { name: 'Trocar titular/reserva' }))
  expect(within(region).getByRole('status')).toHaveTextContent('Ajuste aplicado')
  await user.click(within(region).getByRole('button', { name: 'Voltar aos participantes' }))
  await user.click(screen.getByRole('button', { name: /Remover regra.*jogar juntos/ }))
  await user.click(screen.getByRole('button', { name: 'Continuar editando' }))
  expect(screen.getByRole('button', { name: /Remover regra.*jogar juntos/ })).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  await user.click(screen.getByRole('button', { name: 'Descartar ajustes e continuar' }))
  await user.click(await screen.findByRole('button', { name: 'Novo sorteio' }))
  await screen.findByText(/^3 sorteio/)
  await user.click(screen.getByRole('button', { name: 'Salvar e aceitar sorteio' }))
  await screen.findByRole('alert')
  const [, id, payload] = saveMock.mock.calls[0]!
  expect(payload.draw_runs.map(run => [run.algorithm_version, run.accepted])).toEqual([
    ['classic-rules-v3', false], ['classic-rules-v3', false], ['classic-rules-v3', true],
  ])
  expect(payload.assignments.filter(assignment => assignment.team_index === 1).map(assignment => assignment.player_id).sort())
    .toEqual([players[0]!.id, players[1]!.id])
  expect(payload).not.toHaveProperty('rules')
  await user.click(screen.getByRole('button', { name: 'Tentar salvar novamente' }))
  await screen.findByText(/Partida salva e sorteio aceito/)
  expect(saveMock.mock.calls[1]![1]).toBe(id)
  expect(saveMock.mock.calls[1]![2]).toBe(payload)
})

it('bloqueia o conflito e remove regras vinculadas ao desmarcar um participante', async () => {
  const user = userEvent.setup()
  render(<GameFlow client={client} group={group} players={players} />)
  await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
  await user.click(screen.getByRole('button', { name: 'Selecionar todos' }))
  await addRule(user, 'together', 0, players[1]!.id)
  await addRule(user, 'apart', 0, players[1]!.id)
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  expect(await screen.findByRole('alert')).toHaveTextContent(/Pessoa 1 e Pessoa 2.*juntos e separados/)
  await user.click(screen.getByRole('checkbox', { name: /Pessoa 2/ }))
  expect(screen.queryByRole('button', { name: /Remover regra/ })).not.toBeInTheDocument()
  expect(screen.getByRole('status')).toHaveTextContent(/removidas regras/)
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  await screen.findByRole('region', { name: 'Resultado do sorteio' })
})

it('invalida uma regra de jogador desativado e remove a regra do Time Verde ao voltar para dois times', async () => {
  const user = userEvent.setup()
  const view = render(<GameFlow client={client} group={group} players={players} />)
  await user.selectOptions(screen.getByRole('combobox', { name: 'Times' }), '3')
  await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
  await user.click(screen.getByRole('button', { name: 'Selecionar todos' }))
  await addRule(user, 'fixed', 0, '2')
  await addRule(user, 'apart', 1, players[2]!.id)
  view.rerender(<GameFlow client={client} group={group}
    players={players.map((player, i) => i === 2 ? { ...player, active: false } : player)} />)
  expect(screen.getByText(/Indisponível. Remova esta regra/)).toBeInTheDocument()
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  expect(await screen.findByRole('alert')).toHaveTextContent(/jogador indisponível/)
  await user.click(screen.getByRole('button', { name: /Remover regra.*jogar separados/ }))
  await user.click(screen.getByRole('button', { name: 'Voltar' }))
  await user.selectOptions(screen.getByRole('combobox', { name: 'Times' }), '2')
  await user.click(screen.getByRole('button', { name: 'Selecionar participantes' }))
  expect(screen.queryByRole('button', { name: /Remover regra/ })).not.toBeInTheDocument()
  expect(screen.getByRole('status')).toHaveTextContent(/times desativados/)
  await user.click(screen.getByRole('button', { name: 'Sortear times' }))
  await screen.findByRole('region', { name: 'Resultado do sorteio' })
})
